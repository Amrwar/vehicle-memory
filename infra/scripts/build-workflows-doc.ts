/**
 * Writes docs/02-design/11-workflows.md from the press-count table in core.
 * Phase 34.
 *
 *   npm run docs:workflows
 *
 * The table lives in code so a test can hold the product to it; the document
 * is generated from it so the two cannot drift. Edit
 * packages/core/src/job/workflow.ts, not the Markdown.
 */

import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { pressesBefore, pressesFor, WORKFLOWS, workflowsAsMarkdown } from '@carnet/core';

const OUT = resolve(__dirname, '../../docs/02-design/11-workflows.md');

const before = WORKFLOWS.reduce((total, w) => total + pressesBefore(w), 0);
const now = WORKFLOWS.reduce((total, w) => total + pressesFor(w), 0);

const doc = `# The five workflows, counted in presses

_Generated by \`infra/scripts/build-workflows-doc.ts\` from
\`packages/core/src/job/workflow.ts\`. Do not edit by hand; edit the table in
core and run \`npm run docs:workflows\`._

A workshop does not buy features. It buys the number of times somebody at the
counter has to press something, and the number of screens they have to find,
between a car arriving and the money being in the bank. This document is that
count, hand-off by hand-off, for the five workflows the product is judged on.

A **press** is one deliberate act by a person: a button, a link, a choice in a
list. Typing into a field is not a press; the button that submits it is. A
**hand-off** is the moment the work passes from one person or screen to the
next. Each hand-off names the one screen it happens on.

**Before** is the count at the end of Phase 33. **Now** is the count after
Phase 34. Across the five workflows: ${before} presses before, ${now} now.

The walkthrough script \`infra/scripts/verify-workflow.ts\` takes a job from a
booking to a paid bill through the same library functions the pages call,
records each hand-off with the presses it cost and the screen it happened on,
and fails on any step that costs more than the table says or that needs a
screen the table does not name. The unit test \`workflow.test.ts\` fails if any
hand-off ever costs more than it did before.

${workflowsAsMarkdown()}
## Reading the table

- A hand-off at **0** presses is one the system does on the person's behalf:
  the approval that puts the lines on the job and reserves the parts, the
  payment that closes the job and writes the passport entry.
- The customer's own presses are counted on their phone and are not the
  workshop's to reduce below two: choose, then confirm, is the least a person
  should do before spending money.
- A hand-off whose count did not change is written down anyway. The next
  phase that adds a screen to one of these has to say why here.
`;

writeFileSync(OUT, doc, 'utf8');
console.info(`  wrote ${OUT} (${before} presses before, ${now} now)`);

"""
Keeps the business case's build-status section true.

    python infra/scripts/update-business-case.py

The document is written by hand and should stay that way: it is an argument,
not a report. One section is the exception, because it states what is built,
and a hand-typed statement of what is built goes stale the same week.

So that section is generated from the repository and rewritten in place, and
everything above it is left alone. If Word has the file open, close it first;
Word will otherwise overwrite this on its next save.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

sys.path.insert(0, str(Path(__file__).resolve().parent))

from build_deck import (  # noqa: E402
    count_checks,
    count_feature_lines,
    count_models,
    count_requirements,
    count_routes,
    count_tests,
)

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / 'docs' / 'Carnet-Business-Case.docx'

HEADING = 'Build status'
PETROL = RGBColor(0x1A, 0x4D, 0x52)
SOFT = RGBColor(0x53, 0x5E, 0x60)


def remove(paragraph) -> None:
    element = paragraph._element
    element.getparent().remove(element)


def drop_existing(document) -> None:
    """Removes a previously generated section, so re-running does not stack."""
    found = False
    doomed = []

    for paragraph in document.paragraphs:
        if paragraph.style.name == 'Heading 1':
            # The generated section runs to the end of the document, so the
            # first Heading 1 that matches begins the part to replace.
            found = paragraph.text.strip().endswith(HEADING)
            if found:
                doomed.append(paragraph)
            continue

        if found:
            doomed.append(paragraph)

    for paragraph in doomed:
        remove(paragraph)

    if found:
        # Tables inside the removed section have to go too.
        for table in list(document.tables)[-2:]:
            element = table._element
            if element.getparent() is not None:
                element.getparent().remove(element)


def note(document, body: str, italic: bool = False):
    paragraph = document.add_paragraph()
    run = paragraph.add_run(body)
    run.font.size = Pt(10.5)
    run.font.color.rgb = SOFT
    run.italic = italic
    paragraph.paragraph_format.space_after = Pt(8)
    return paragraph


def build() -> None:
    document = docx.Document(DOC)
    drop_existing(document)

    counts = count_feature_lines()
    total = sum(counts.values()) or 1

    heading = document.add_heading(f'13  {HEADING}', level=1)
    for run in heading.runs:
        run.font.color.rgb = PETROL

    note(
        document,
        f'Counted from the repository on {date.today():%d %B %Y}. This section is '
        f'generated by infra/scripts/update-business-case.py and rewritten each time '
        f'the product changes. Everything above it is written by hand.',
        italic=True,
    )

    figures = [
        ('Pages in the application', str(count_routes())),
        ('Database tables', str(count_models())),
        ('Domain tests', f'{count_tests():,}'),
        ('Database invariant probes', str(count_checks())),
        ('Functional requirements', str(count_requirements())),
        ('Capabilities built', f'{counts.get("Built", 0)} of {total}'),
        ('Capabilities partial', str(counts.get('Partial', 0))),
        ('Capabilities not yet built', str(counts.get('Missing', 0))),
    ]

    table = document.add_table(rows=1, cols=2)
    table.style = 'Light Grid Accent 1'

    header = table.rows[0].cells
    header[0].text = 'Measure'
    header[1].text = 'Now'

    for label, value in figures:
        row = table.add_row().cells
        row[0].text = label
        row[1].text = value
        row[1].paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT

    document.add_paragraph()

    section = document.add_heading('What is complete', level=3)
    for run in section.runs:
        run.font.color.rgb = PETROL

    note(
        document,
        'Jobs and the diary, customers and vehicles, the tamper-evident passport, '
        'estimates approved line by line, invoicing and payments, inventory with '
        'weighted average cost, purchasing with three-way match, a double-entry '
        'ledger posting from the work itself, bank reconciliation and period close, '
        'people with dated pay rates and productivity, multiple sites with stock '
        'transfers, counter sales, expenses, the automation engine, CRM with '
        'per-channel consent, the customer portal, and outbound messaging.',
    )

    section = document.add_heading('What is deliberately absent', level=3)
    for run in section.runs:
        run.font.color.rgb = PETROL

    note(
        document,
        'Card payment waits on a payment provider. Payroll export waits on a named '
        'target format. Parts fitment waits on a data source, because guessing it '
        'puts wrong parts on cars. Suggesting a diagnosis from symptoms waits on a '
        'corpus that does not exist yet, and a confident wrong suggestion on a '
        'braking fault is not a small error. Each of these is absent rather than '
        'approximated, on the grounds that a feature nobody can trust is worse than '
        'one that is honestly missing.',
    )

    section = document.add_heading('What is scheduled', level=3)
    for run in section.runs:
        run.font.color.rgb = PETROL

    note(
        document,
        'Phases 7 to 12, ordered by what a workshop loses each day without them. '
        'The digital vehicle inspection is first: six tables already exist and no '
        'interface does, and an inspection is what turns a booked oil change into '
        'approved brake work. Then the calendar and the bay board, then warranty '
        'and fleet, then reviews and loyalty and the inbound inbox, then the '
        'remaining accounting gaps, and last the owner command centre.',
    )

    document.save(DOC)
    print(f'Updated {DOC}')


if __name__ == '__main__':
    build()

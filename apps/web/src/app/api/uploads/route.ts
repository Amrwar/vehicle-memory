import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import { join, normalize } from 'node:path';
import { type NextRequest, NextResponse } from 'next/server';
import { Readable } from 'node:stream';

import { requireSession } from '@/lib/guard';
import { driver, writeLocal } from '@/lib/storage';

/**
 * The local file store, for development.
 *
 * In production the browser uploads straight to S3 or R2 with a signed URL and
 * this route is never called. It exists so the whole photograph flow can be
 * built and walked without anybody opening an account, which is the same
 * reasoning as the console mail transport.
 *
 * It refuses to run when the store is configured for S3, rather than quietly
 * writing to a disk that a serverless host discards between requests. A
 * photograph that disappears silently is worse than one never taken.
 */

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';

/**
 * Keys are generated by the server and always have four segments. Checking
 * anyway, because this route joins a path from a query string and the cost of
 * being wrong is reading any file on the machine.
 */
function safeKey(key: string): string | null {
  if (!key || key.includes('\0')) return null;

  const cleaned = normalize(key).replace(/\\/g, '/');

  if (cleaned.startsWith('/') || cleaned.includes('..')) return null;
  if (!/^[A-Za-z0-9/_-]+\.[A-Za-z0-9]{1,5}$/.test(cleaned)) return null;

  return cleaned;
}

export async function PUT(request: NextRequest) {
  if (driver() !== 'local') {
    return NextResponse.json(
      { error: 'The file store is S3. Upload with the signed URL instead.' },
      { status: 400 },
    );
  }

  // A signed URL carries its own authority; this one does not, so it checks a
  // session the way every other write in the product does.
  await requireSession('job:write');

  const key = safeKey(request.nextUrl.searchParams.get('key') ?? '');
  if (!key) return NextResponse.json({ error: 'Not a usable key.' }, { status: 400 });

  const body = Buffer.from(await request.arrayBuffer());
  await writeLocal(key, body);

  return NextResponse.json({ key, bytes: body.byteLength });
}

export async function GET(request: NextRequest) {
  if (driver() !== 'local') {
    return NextResponse.json({ error: 'Read it from the signed URL.' }, { status: 400 });
  }

  await requireSession('job:read');

  const key = safeKey(request.nextUrl.searchParams.get('key') ?? '');
  if (!key) return NextResponse.json({ error: 'Not a usable key.' }, { status: 400 });

  const path = join(process.env.STORAGE_LOCAL_PATH ?? '.storage', key);

  try {
    const info = await stat(path);

    const stream = Readable.toWeb(createReadStream(path)) as ReadableStream;

    return new NextResponse(stream, {
      headers: {
        'content-length': String(info.size),
        'content-type': key.endsWith('.png') ? 'image/png' : 'image/jpeg',
        // Signed URLs expire; this one is session-guarded, so it must not be
        // cached anywhere a different person could reach it.
        'cache-control': 'private, max-age=300',
      },
    });
  } catch {
    return NextResponse.json({ error: 'No such file.' }, { status: 404 });
  }
}
